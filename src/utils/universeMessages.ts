export const getDailyQuote = (): string => {
  const quotes = [
    "Сила воли — это мышца, которая растёт с каждым днём аскезы.",
    "В твоём отказе больше силы, чем в тысяче действий других.",
    "То, что ты преодолеваешь сегодня, завтра станет твоим источником силы.",
    "Аскеза не обедняет, а обогащает твою внутреннюю вселенную.",
    "Когда ты отпускаешь низкое, высшее находит к тебе дорогу.",
    "Вселенная уважает решимость и вознаграждает стойкость.",
    "Каждый день аскезы — это шаг к твоему истинному я."
  ];
  
  // Use current date as seed for consistent daily quote
  const today = new Date().toDateString();
  let seed = 0;
  for (let i = 0; i < today.length; i++) {
    seed += today.charCodeAt(i);
  }
  
  return quotes[seed % quotes.length];
};
